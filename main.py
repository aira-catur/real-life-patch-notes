import os

TEXT = "v4.2.0: Fixed bug where passing through a doorway wiped short-term memory; the reason you entered the room is no longer deleted on arrival."

def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(TEXT)

if __name__ == "__main__":
    main()
